// Generates the nginx pieces that mirror vercel.json for a self-hosted static server:
//   redirects.conf          one exact-match location per permanent redirect
//   security-headers.conf   the site-wide response headers (the CSP among them)
//   cache-locations.conf    one location per Cache-Control rule
// Usage: node scripts/nginx-conf.mjs <outDir> [--analytics=off|on]
// With analytics off (also PUBLIC_ANALYTICS=off in the environment) the stats host is left out of the CSP.
// The Dockerfile runs this at image build time, so the config cannot drift from vercel.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const STATS_HOST = 'https://stats.keenankaufman.com';

const q = (s) => {
  if (/[\n\r"\\$]/.test(s)) throw new Error(`Refusing to write ${JSON.stringify(s)} into nginx config`);
  return `"${s}"`;
};

/** Build the three config files as strings. */
export function buildNginxConf(vercel, { analytics = true } = {}) {
  const out = { redirects: [], security: [], cache: [] };
  const banner = '# Generated by scripts/nginx-conf.mjs from vercel.json. Do not edit.';

  out.redirects.push(banner);
  const seen = new Set();
  for (const r of vercel.redirects ?? []) {
    // The host-matched rule only exists for Vercel's own preview domain.
    if (r.has) continue;
    if (!r.permanent) throw new Error(`Temporary redirect ${r.source} is not supported by the generator`);
    if (!/^\/[A-Za-z0-9._~\/-]*$/.test(r.source)) throw new Error(`Unsupported redirect source ${r.source}`);
    if (seen.has(r.source)) throw new Error(`Duplicate redirect source ${r.source}`);
    seen.add(r.source);
    out.redirects.push(`location = ${r.source} { return 301 ${q(r.destination)}; }`);
  }

  out.security.push(banner);
  out.security.push('# Included in every location that sets its own add_header (nginx drops the inherited ones there).');
  out.cache.push(banner);
  for (const rule of vercel.headers ?? []) {
    const headers = rule.headers.map((h) => {
      let value = h.value;
      if (!analytics && h.key.toLowerCase() === 'content-security-policy') value = value.split(` ${STATS_HOST}`).join('');
      return `add_header ${h.key} ${q(value)} always;`;
    });
    if (rule.source === '/(.*)') {
      out.security.push(...headers);
      continue;
    }
    let loc;
    if (/^\/[A-Za-z0-9_-]+\/\(\.\*\)$/.test(rule.source)) loc = `^~ ${rule.source.replace('(.*)', '')}`;
    else if (/^\/[A-Za-z0-9._-]+$/.test(rule.source)) loc = `= ${rule.source}`;
    else throw new Error(`Unsupported header source ${rule.source}`);
    out.cache.push(`location ${loc} {`, ...headers.map((h) => `  ${h}`), '  include /etc/nginx/stayput/security-headers.conf;', '  try_files $uri =404;', '}');
  }
  return Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.join('\n') + '\n']));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const dir = process.argv[2];
  if (!dir) throw new Error('Usage: node scripts/nginx-conf.mjs <outDir> [--analytics=off|on]');
  const flag = process.argv.find((a) => a.startsWith('--analytics='))?.split('=')[1] ?? (process.env.PUBLIC_ANALYTICS === 'off' ? 'off' : 'on');
  const vercel = JSON.parse(readFileSync(fileURLToPath(new URL('../vercel.json', import.meta.url)), 'utf8'));
  const conf = buildNginxConf(vercel, { analytics: flag !== 'off' });
  mkdirSync(dir, { recursive: true });
  writeFileSync(`${dir}/redirects.conf`, conf.redirects);
  writeFileSync(`${dir}/security-headers.conf`, conf.security);
  writeFileSync(`${dir}/cache-locations.conf`, conf.cache);
  console.log(`nginx-conf: ${conf.redirects.split('\n').filter((l) => l.startsWith('location')).length} redirects, analytics ${flag}`);
}
